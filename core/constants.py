"""
Constants for tactile map generation.

Спецификация тактильной карты для незрячих.
"""

# === РАЗМЕРЫ КАРТЫ ===
CARD_WIDTH_MM = 200    # Ширина одной карточки
CARD_HEIGHT_MM = 160   # Высота одной карточки
GRID_COLS = 2          # Колонок в сетке
GRID_ROWS = 2          # Рядов в сетке
FULL_WIDTH_MM = CARD_WIDTH_MM * GRID_COLS   # 400 мм
FULL_HEIGHT_MM = CARD_HEIGHT_MM * GRID_ROWS  # 320 мм
BASE_THICKNESS_MM = 6.0  # Толщина основания (увеличена для пазов)

# === ПАЗЛОВЫЕ СОЕДИНЕНИЯ ===
# Ласточкин хвост (2026-08-04): прямоугольные шипы свободно выезжали вбок —
# собранная карта разъезжалась. Теперь шип — трапеция (у кромки узкая, к концу
# широкая): сборка ОПУСКАНИЕМ сверху (паз открыт снизу), вбок не расходится.
TAB_HEIGHT_MM = 3.0        # Высота выступа (по Z)
TAB_DEPTH_MM = 4.0         # Глубина выступа (насколько торчит)
TAB_WIDTH_MM = 8.0         # Ширина шейки у кромки карточки
TAB_HEAD_WIDTH_MM = 13.0   # Ширина головки на конце (шире шейки → замок)
SLOT_CLEARANCE_MM = 0.5    # Зазор в плане для вхождения tab в slot
SLOT_Z_CLEARANCE_MM = 0.2  # Вертикальный зазор паза (слоновья нога 1-го слоя)

# === ТАКТИЛЬНЫЕ ПАРАМЕТРЫ ===

# Границы стран — главная ЛИНИЯ, но без доминирования по высоте.
# Ребаланс 2026-06-19: было 9 мм (в 3× выше гор 3 мм) → рельеф не читался.
# Теперь гребень 4.5 мм = всего +1.5 мм над самой высокой горой (3 мм):
# граница остаётся непрерывным трассируемым гребнем, но горы снова ощущаются.
BOUNDARY_HEIGHT_MM = 4.5   # верх ribbon-столбика границы (см. RIBBON_TOP_Z)
BOUNDARY_WIDTH_MM = 1.5    # Ширина границ (было 2.5 — давило, особенно на Балканах)
# Ребаланс-2 (2026-06-19): граница СЛЕДУЕТ ЗА РЕЛЬЕФОМ — тонкий гребень
# постоянной высоты BOUNDARY_RELIEF_MM над МЕСТНЫМ рельефом, а не плоскость
# на фиксированной абсолютной высоте. Раньше над низиной/морем граница была
# стеной +4.5 мм → палец не залезал в равнинные мелкие страны. Теперь везде
# одинаковый низкий гребень: палец скользит и по рельефу, и по границе.
BOUNDARY_RELIEF_MM = 1.2   # Высота гребня границы НАД местным рельефом

# Рельеф — фоновый элемент
MAX_ELEVATION_MM = 4.0     # Максимальная высота рельефа (верхняя граница top-плато)
TERRAIN_LEVELS = 4         # Квантование рельефа: 4 плато вместо непрерывного градиента
                           # Значения плато: 0, 1, 2, 3 мм (floor каждого бина шириной 1 мм)
                           # 1 мм > 2 × MIN_TACTILE_DIFFERENCE_MM → пальцу читаемо
                           # Семантика: море / низменность / плато / горы
                           # При 0.2 мм слое FDM каждая ступень = ровно 5 слоёв

# Граница проходит сквозь плиту и рельеф от внутренности плиты до единой
# горизонтальной плоскости (гребня) над самым высоким рельефом.
# Низ: −5.99 мм (на 0.01 мм выше дна плиты, избегает coplanar-граней).
# Верх: 4.5 мм — единый гребень, по которому палец трассирует границу
# независимо от рельефа под ней; +1.5 мм над горами (3 мм), так что
# рельеф между границами остаётся читаемым (ребаланс 2026-06-19).
RIBBON_BOTTOM_Z = -BASE_THICKNESS_MM + 0.01      # -5.99
RIBBON_TOP_Z = BOUNDARY_HEIGHT_MM                # 4.5 (было MAX_ELEVATION+BOUNDARY=9)

# Вода — волновой паттерн
WAVE_HEIGHT_MM = 2.0       # Высота волны
WAVE_INTERVAL_MM = 4.0     # Расстояние между волнами

# === БРАЙЛЬ (Marburg Medium) ===
# Ребаланс 2026-08-04: раньше точки были КОНУСАМИ с остриём (radius 1.0,
# height 1.2, шаг точек 1.5-1.8 мм) — палец ловил только острый кончик,
# точки сливались. Теперь стандарт Marburg Medium: купол ⌀1.6 мм высотой
# 0.8 мм, шаг точек в ячейке 2.5 мм, шаг ячеек 6.0 мм.
BRAILLE_DOT_RADIUS_MM = 0.8   # радиус основания купола (⌀1.6)
BRAILLE_DOT_HEIGHT_MM = 0.8   # высота купола НАД поверхностью
BRAILLE_DOT_PITCH_MM = 2.5    # шаг точек внутри ячейки (обе оси)
BRAILLE_CELL_PITCH_MM = 6.0   # шаг ячеек (точка 1 → точка 1 соседней)
# Якорный гребень слева от метки (2026-08-05). Изолированная ячейка на карте
# не имеет ни строки, ни соседей, ни базовой линии — палец не может понять,
# какая из 6 позиций занята. Гребень во всю высоту ячейки задаёт левый край и
# уровни верхней/нижней строки: найдя его, читатель знает систему координат.
# Один гребень на всю метку — строки у всех ячеек общие, а шаг ячеек 6 мм сам
# разделяет столбцы.
BRAILLE_ANCHOR_WIDTH_MM = 1.0   # толщина гребня
BRAILLE_ANCHOR_GAP_MM = 1.4     # просвет от гребня до края ближайшей точки

# Чистое поле вокруг метки. Руководства по тактильной графике требуют «a gap of
# at least 3 mm all round» для символа, который надо распознать, но на карте это
# конкурирует с размером стран: замер 2026-08-05 показал 20 подписей при 3 мм
# против 27 при 1.2 мм. Поэтому не одно значение на всех, а ЛЕСТНИЦА: каждой
# стране даётся максимальный просвет, который в неё влезает. Крупные получают
# полные 3 мм, мелкие — минимум, при котором метка ещё держится.
LABEL_CLEARANCE_LADDER_MM = (3.0, 2.5, 2.0, 1.5, 1.2)

# Юбка-цилиндр под куполом: уходит вниз в тело, чтобы union гарантированно
# приварил точку и чтобы embed/ступень рельефа не съедали высоту купола.
# Глубина = MAX_ELEVATION (3) + 1.2: даже у метки на самом высоком плато низ
# юбки < BASE_TOP_GUARD (-1.0), heal_mesh НЕ сдвигает тело вниз на embed —
# купол всегда торчит ровно на BRAILLE_DOT_HEIGHT_MM. Юбка прячется в плите
# (низ ≥ -4.2 > -6), в печати не видна.
BRAILLE_SKIRT_MM = 4.2

# === ИЕРАРХИЯ ВЫСОТ (от верха плиты, z = 0) ===
# 0/1/2/3 мм — 4 плато рельефа (море / низменность / плато / горы)
# +2.0 мм    — волны воды над морем (WAVE_HEIGHT_MM)
# +1.2 мм    — гребень границы НАД МЕСТНЫМ рельефом (BOUNDARY_RELIEF_MM);
#              не плоскость на фиксированной высоте — палец читает рельеф
#              по обе стороны от границы
# +0.8 мм    — купола брайля над своей площадкой (BRAILLE_DOT_HEIGHT_MM)

# === ТЕХНИЧЕСКИЕ ПАРАМЕТРЫ ===
MIN_TACTILE_DIFFERENCE_MM = 0.5  # Минимальная различимая разница высот
